def cpp_literal(data: bytes) -> str:
    """Emit bytes as one escaped C++ string literal (no literal newlines)."""
    out = ['"']
    for byte in data:
        if byte == 0x22:
            out.append('\\"')
        elif byte == 0x5C:
            out.append("\\\\")
        elif byte == 0x0A:
            out.append("\\n")
        elif byte == 0x0D:
            out.append("\\r")
        elif byte == 0x09:
            out.append("\\t")
        elif 0x20 <= byte <= 0x7E:
            out.append(chr(byte))
        else:
            out.append(f"\\{byte:03o}")
    out.append('"')
    return "".join(out)


def decode_lines(path: pathlib.Path) -> tuple[dict[str, tuple[bytes, bytes]], str]:
    raw = path.read_bytes()
    found: dict[str, tuple[bytes, bytes]] = {}
    for line in raw.decode("utf-8", "replace").splitlines():
        if not line.startswith("CUE|"):
            continue
        _, name, compact, pretty = line.split("|")
        found[name] = (base64.b64decode(compact), base64.b64decode(pretty))
    return found, hashlib.sha256(raw).hexdigest()


def render(
    expectations: dict[str, tuple[bytes, bytes]],
    capture_note: str,
) -> bytes:
    lines: list[str] = []
    lines.append("// Generated by out/verification-20261101/r3-prepare-cost-v1/")
    lines.append("// gen_serialize_golden.py -- do not edit by hand.")
    lines.append("//")
    lines.append("// Golden bytes for json::serialize, one entry per pre-registered corpus case. The")
    lines.append("// corpus itself lives in out/verification-20261101/r3-prepare-cost-v1/")
    lines.append("// gen_serialize_golden.py; `source` is the JSON input and `compact` / `pretty`")
    lines.append("// are the exact expected output bytes of SerializeStyle::Compact and")
    lines.append("// SerializeStyle::Pretty.")
    lines.append("//")
    lines.append("// The goldens were captured from the reference implementation of json::serialize")
    lines.append("// (a double-tree dump through the previous DOM library) before the direct writer")
    lines.append("// replaced it, so they")
    lines.append("// pin the bytes that the chart canonical identity depends on.")
    if capture_note:
        for note_line in capture_note.splitlines():
            lines.append(f"// {note_line}")
    lines.append("#pragma once")
    lines.append("")
    lines.append("#include <cstddef>")
    lines.append("#include <string_view>")
    lines.append("")
    lines.append("namespace cuexis_json_golden {")
    lines.append("")
    lines.append("struct Case final {")
    lines.append("    std::string_view name;")
    lines.append("    std::string_view source;")
    lines.append("    std::string_view compact;")
    lines.append("    std::string_view pretty;")
    lines.append("};")
    lines.append("")
    lines.append("inline constexpr Case kCases[] = {")
    for name, source in CASES:
        compact, pretty = expectations.get(name, (b"", b""))
        lines.append("    {")
        lines.append(f"        {cpp_literal(name.encode('utf-8'))},")
        lines.append(f"        {cpp_literal(source.encode('utf-8'))},")
        lines.append(f"        {cpp_literal(compact)},")
        lines.append(f"        {cpp_literal(pretty)},")
        lines.append("    },")
    lines.append("};")
    lines.append("inline constexpr std::size_t kCaseCount = sizeof(kCases) / sizeof(kCases[0]);")
    lines.append("")
    lines.append("} // namespace cuexis_json_golden")
    lines.append("")
    return ("\n".join(lines)).encode("utf-8")


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--emit-header", required=True)
    parser.add_argument("--capture")
    parser.add_argument("--capture-note", action="append", default=[])
    parser.add_argument("--clang-format")
    parser.add_argument("--check-round-trip", action="store_true")
    args = parser.parse_args(argv)

    expectations: dict[str, tuple[bytes, bytes]] = {}
    if args.capture:
        expectations, capture_sha = decode_lines(pathlib.Path(args.capture))
        note = "\n".join(
            line.replace("{capture_sha256}", capture_sha) for line in args.capture_note
        )
        missing = [name for name, _ in CASES if name not in expectations]
        if missing:
            print(f"capture is missing cases: {missing}", file=sys.stderr)
            return 1
        unknown = sorted(set(expectations) - {name for name, _ in CASES})
        if unknown:
            print(f"capture has unknown cases: {unknown}", file=sys.stderr)
            return 1
    else:
        note = "UNCAPTURED: expectations are empty until the capture is frozen."
    header = pathlib.Path(args.emit_header)
    header.write_bytes(render(expectations, note))

    if args.clang_format:
        subprocess.run([args.clang_format, "-i", "--style=file", str(header)], check=True)
        if args.check_round_trip:
            once = header.read_bytes()
            subprocess.run([args.clang_format, "-i", "--style=file", str(header)], check=True)
            if header.read_bytes() != once:
                print("clang-format is not idempotent on the header", file=sys.stderr)
                return 1

    print(f"wrote {header} ({header.stat().st_size} bytes, {len(CASES)} cases)")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
