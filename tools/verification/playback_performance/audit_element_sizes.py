"""Static element-size audit for the PD-5 memory-cap ledger.

The B0 ledger (``memory_caps.py``) multiplies a declared capacity by an audited element size.  This
tool produces that audited size: it compiles one translation unit with the same MSVC toolchain,
standard and preprocessor definitions as the Release profile, prints ``sizeof`` for the element
types that the reference workload actually stores, and records the result as
``element_sizes.v1.json``.  No workload runs, nothing is allocated or observed; the only product of
this tool is a set of compile-time constants plus the compiler identity that produced them.

Usage (from a checkout, inside or outside a Developer shell)::

    python -B tools/verification/playback_performance/audit_element_sizes.py --write
    python -B tools/verification/playback_performance/audit_element_sizes.py --check
    python -B tools/verification/playback_performance/audit_element_sizes.py --markdown

``--check`` recompiles and compares, so the recorded sizes are reproducible rather than pasted.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import os
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

SCHEMA = "pd5.element-sizes.v1"
ROOT = Path(__file__).resolve().parents[3]
OUTPUT = Path(__file__).resolve().parent / "element_sizes.v1.json"

DEFAULT_VSDEVCMD = Path(
    r"D:\Program Files\Microsoft Visual Studio\18\Community\Common7\Tools\VsDevCmd.bat")
DEFAULT_VCPKG_INCLUDE = Path(r"D:\vcpkg\installed\x64-windows\include")

#: Release-profile preprocessor definitions, copied from the compile command that the Release
#: build recorded for ``app/execution_host/frame_delivery.cpp``.  They are repeated here so the
#: audit does not depend on a configured build tree; ``--check`` would drift if the build changed
#: a definition that alters a layout.
DEFINITIONS = (
    "CUEXIS_AUDIO_STATIC_DEFINE",
    "CUEXIS_CONTENT_STATIC_DEFINE",
    "CUEXIS_CORE_STATIC_DEFINE",
    "CUEXIS_EXPERIMENTAL_BUILD=1",
    "CUEXIS_PLAYBACK_GAMEPLAY_CANDIDATE=1",
    "CUEXIS_PLAYBACK_STATIC_DEFINE",
    "NOMINMAX",
    "WIN32_LEAN_AND_MEAN",
    "WIN32",
    "_WINDOWS",
    "NDEBUG",
)

#: Element types the reference workload stores, and the ledger cell each one bounds.  The unit is
#: a whole object including its inline members; container nodes and vector slack are charged
#: separately by the caller through the declared capacity.
ELEMENTS = (
    ("HostContext", "ControlRequest、StepKey、ConsumerRegistration 的内嵌 context"),
    ("ControlRequest", "command.session 队列元素"),
    ("ControlReceipt", "receipt 保留单元"),
    ("StepRequest", "ControlReceipt::steps 元素"),
    ("StepReceipt", "ControlReceipt::steps 元素（含 effects）"),
    ("DeliveryInfo", "history.request 元素的一半"),
    ("DeliveryFingerprint", "history.request 元素的一半"),
    ("PresentReceipt", "receipt 保留槽元素"),
    ("SessionCommand", "SessionWorker 队列元素（variant，取最大分支）"),
)

#: ``history.request`` stores ``std::optional<RequestRecord>`` and ``RequestRecord`` is a private
#: nested type.  The mirror repeats its member sequence exactly; both are non-virtual standard
#: layout aggregates, so the standard fixes an identical size and alignment.
MIRROR = """struct RequestRecordMirror final {
    DeliveryFingerprint fingerprint;
    DeliveryInfo info;
};
"""

PROBE_TEMPLATE = """// Generated by audit_element_sizes.py.  Prints PD-5 element sizes as one JSON object.
#include <cstddef>
#include <cstdio>
#include <optional>
#include <string>
#include <variant>

#include <cuexis/playback/execution_control.hpp>
#include <cuexis/playback/execution_coordination.hpp>
#include <cuexis/playback/gameplay_candidate.hpp>
#include <frame_delivery.hpp>
#include <session_worker.hpp>

namespace cuexis::playback::detail {
__MIRROR__
} // namespace cuexis::playback::detail
"""


def _digest(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def _source() -> str:
    mirror = MIRROR.replace("DeliveryFingerprint", "cuexis::playback::detail::DeliveryFingerprint")
    mirror = mirror.replace("DeliveryInfo", "cuexis::playback::detail::DeliveryInfo")
    body = PROBE_TEMPLATE.replace("__MIRROR__", mirror.strip())
    rows = []
    for name, _ in ELEMENTS:
        rows.append(f'    {{"{name}", sizeof({name})}},')
    rows.append(
        '    {"optional_RequestRecord", '
        "sizeof(std::optional<cuexis::playback::detail::RequestRecordMirror>)},"
    )
    rows.append(
        '    {"optional_PresentReceipt", sizeof(std::optional<PresentReceipt>)},'
    )
    body += (
        "\nusing namespace cuexis::playback;\n"
        "using namespace cuexis::playback::detail;\n"
        "\nnamespace {\n"
        "struct Row final {\n"
        "    const char* name;\n"
        "    std::size_t size;\n"
        "};\n"
        "const Row rows[] = {\n" + "\n".join(rows) + "\n};\n"
        "} // namespace\n\n"
        "int main() {\n"
        '    std::printf("{\\"compiler\\": \\"%llu\\", \\"sizes\\": {",\n'
        "                static_cast<unsigned long long>(_MSC_FULL_VER));\n"
        "    bool first = true;\n"
        "    for (const auto& row : rows) {\n"
        '        std::printf("%s\\"%s\\": %zu", first ? "" : ", ", row.name, row.size);\n'
        "        first = false;\n"
        "    }\n"
        '    std::printf("}}\\n");\n'
        "    return 0;\n"
        "}\n"
    )
    return body


def _generated_dir(explicit: Path | None) -> Path:
    if explicit is not None:
        generated = explicit.resolve()
        header = generated / "cuexis" / "playback" / "playback_export.hpp"
        if not header.is_file():
            raise SystemExit(f"generated export header not found: {header}")
        return generated
    candidates = sorted(
        (path for path in ROOT.glob("out/build/*/generated")
         if (path / "cuexis" / "playback" / "playback_export.hpp").is_file()),
    )
    if not candidates:
        raise SystemExit("no configured build tree with generated export headers; pass --generated")
    if len(candidates) != 1:
        choices = ", ".join(str(path) for path in candidates)
        raise SystemExit(f"multiple configured build trees; pass --generated explicitly: {choices}")
    return candidates[0]


def _includes(vcpkg_include: Path, generated: Path) -> list[Path]:
    found = sorted(ROOT.glob("engine/*/include"))
    extra = [ROOT / "engine" / "core" / "internal", ROOT / "app" / "execution_host", generated]
    ordered = [path for path in extra if path.is_dir()]
    ordered += found
    ordered.append(vcpkg_include)
    return ordered


def _compile(tu: Path, includes: list[Path], workdir: Path) -> tuple[dict, str]:
    response = workdir / "probe.rsp"
    lines = ["/nologo", "/TP", "/std:c++20", "/EHsc", "/MD", "/O2", "/DNDEBUG"]
    lines += [f"/D{define}" for define in DEFINITIONS]
    lines += [f"/I{path}" for path in includes]
    lines += ["/utf-8", f"/Fo{workdir / 'probe.obj'}", f"/Fe{workdir / 'probe.exe'}"]
    lines += [str(tu)]
    response.write_text("\n".join(lines) + "\n", encoding="ascii")

    # A batch file avoids the nested-quote mangling that ``cmd /c call "path"`` suffers when the
    # command line is assembled by a child process; the scratch directory carries no spaces.
    batch = workdir / "build.bat"
    batch.write_text(
        "@echo off\r\n"
        f'call "{DEFAULT_VSDEVCMD}" -arch=amd64 -no_logo >nul || exit /b 1\r\n'
        "cl.exe @probe.rsp\r\n",
        encoding="ascii",
    )
    completed = subprocess.run(
        ["cmd.exe", "/c", batch.name],
        cwd=workdir,
        capture_output=True,
        text=True,
        encoding="utf-8",
        errors="replace",
    )
    if completed.returncode != 0:
        detail = (completed.stdout or "") + (completed.stderr or "")
        raise SystemExit(f"element-size probe failed to compile:\n{detail[-4000:]}")

    executable = workdir / "probe.exe"
    if not executable.exists():
        raise SystemExit("element-size probe produced no executable")
    ran = subprocess.run([str(executable)], capture_output=True, text=True, encoding="utf-8")
    if ran.returncode != 0:
        raise SystemExit(f"element-size probe failed at run time: {ran.stderr[-1000:]}")
    return json.loads(ran.stdout), (completed.stdout or "")


def measure(vcpkg_include: Path, generated: Path | None = None) -> dict:
    if not DEFAULT_VSDEVCMD.is_file():
        raise SystemExit(f"Visual Studio developer shell not found: {DEFAULT_VSDEVCMD}")
    if not vcpkg_include.is_dir():
        raise SystemExit(f"vcpkg include directory not found: {vcpkg_include}")
    includes = _includes(vcpkg_include, _generated_dir(generated))
    source = _source()
    with tempfile.TemporaryDirectory(prefix="pd5-size-audit-") as scratch:
        workdir = Path(scratch)
        tu = workdir / "pd5_element_sizes.cpp"
        tu.write_text(source, encoding="ascii")
        probe, _ = _compile(tu, includes, workdir)

    sizes = probe["sizes"]
    expected = [name for name, _ in ELEMENTS] + [
        "optional_RequestRecord", "optional_PresentReceipt"]
    missing = [name for name in expected if name not in sizes]
    if missing:
        raise SystemExit(f"probe did not report: {', '.join(missing)}")
    if any(not isinstance(value, int) or value <= 0 for value in sizes.values()):
        raise SystemExit("probe reported a non-positive size")

    return {
        "schema": SCHEMA,
        "scope": "compile-time element sizes only; no workload, no allocation, no observation",
        "toolchain": {
            "family": "MSVC",
            "msc_full_version": int(probe["compiler"]),
            "arguments": "/std:c++20 /EHsc /MD /O2 /DNDEBUG",
        },
        "definitions": list(DEFINITIONS),
        "include_directories": [str(path) for path in includes],
        "sources": {
            "cuexis/playback/execution_control.hpp": (
                "ControlRequest、ControlReceipt、StepRequest、StepReceipt"),
            "app/execution_host/frame_delivery.hpp": "DeliveryInfo、DeliveryFingerprint",
            "app/execution_host/session_worker.hpp": "SessionCommand",
        },
        "elements": [
            {"type": name, "bytes": sizes[name], "bounds": description}
            for name, description in ELEMENTS
        ] + [
            {
                "type": "std::optional<RequestRecord>",
                "bytes": sizes["optional_RequestRecord"],
                "bounds": "history.request 单槽（私嵌套类型的等价镜像）",
                "mirror_of": "cuexis::playback::detail::FrameDelivery::RequestRecord",
                "mirror_is_exact": True,
            },
            {
                "type": "std::optional<PresentReceipt>",
                "bytes": sizes["optional_PresentReceipt"],
                "bounds": "receipt 保留槽（按 receiptCapacity 定容）",
            },
        ],
        "probe_sha256": _digest(_source().encode("ascii")),
        "tool_sha256": _digest(Path(__file__).read_bytes()),
        "notes": [
            "RequestRecord 是 FrameDelivery 的私有嵌套类型；镜像按成员顺序复写"
            "（DeliveryFingerprint + DeliveryInfo），两者均为非虚标准布局聚合，"
            "标准保证其大小与对齐一致",
            "SessionCommand 是 variant，取最大分支即为队列元素的静态上界",
            "容器节点、vector 冗余容量与分配器头部不在上述尺寸内，由上层容量声明另行计费",
        ],
    }


def check(document: dict, reference: dict) -> list[str]:
    problems = []
    if document.get("schema") != SCHEMA:
        problems.append(f"schema 不是 {SCHEMA}")
    have = {item["type"]: item for item in document.get("elements", [])}
    want = {item["type"]: item for item in reference.get("elements", [])}
    for name in sorted(set(want) - set(have)):
        problems.append(f"缺少元素 {name}")
    for name in sorted(set(have) & set(want)):
        if have[name]["bytes"] != want[name]["bytes"]:
            problems.append(
                f"{name} 记录 {have[name]['bytes']} B，实测 {want[name]['bytes']} B")
    if document.get("toolchain") != reference.get("toolchain"):
        problems.append("工具链身份不一致")
    return problems


def markdown(document: dict) -> str:
    lines = ["| 类型 | 字节 | 界定的账本单元 |", "| --- | --- | --- |"]
    for item in document["elements"]:
        lines.append(f"| `{item['type']}` | {item['bytes']} | {item['bounds']} |")
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--write", action="store_true", help="重新测量并写 element_sizes.v1.json")
    parser.add_argument("--check", action="store_true", help="重新测量并与文件比对")
    parser.add_argument("--markdown", action="store_true", help="输出报告用表格")
    parser.add_argument("--vcpkg-include", type=Path, default=DEFAULT_VCPKG_INCLUDE)
    parser.add_argument("--generated", type=Path,
                        help="configured build's generated directory; required when several exist")
    args = parser.parse_args()
    if not (args.write or args.check or args.markdown):
        parser.error("需要 --write、--check 或 --markdown 之一")

    sys.stdout.reconfigure(encoding="utf-8")
    reference = measure(args.vcpkg_include, args.generated)

    if args.check:
        if not OUTPUT.is_file():
            print(f"缺少 {OUTPUT.name}，先运行 --write", file=sys.stderr)
            return 1
        stored = json.loads(OUTPUT.read_text(encoding="utf-8"))
        problems = check(stored, reference)
        if problems:
            for problem in problems:
                print(f"尺寸不一致：{problem}", file=sys.stderr)
            return 1
        print(f"元素尺寸一致：{OUTPUT.name}")
        return 0

    if args.write:
        OUTPUT.write_text(
            json.dumps(reference, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
        print(f"wrote {OUTPUT}")
        return 0

    print(markdown(reference))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
